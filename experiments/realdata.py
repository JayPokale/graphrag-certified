# RD2: PEGASE real transmission topology
# ===========================================================================
def load_pegase(name):
    import pandapower.networks as pn
    net = getattr(pn, name)()
    E = set()
    for _, r in net.line.iterrows():
        a, b = int(r.from_bus), int(r.to_bus)
        if a != b:
            E.add((min(a, b), max(a, b)))
    for _, r in net.trafo.iterrows():
        a, b = int(r.hv_bus), int(r.lv_bus)
        if a != b:
            E.add((min(a, b), max(a, b)))
    adj = defaultdict(set)
    for a, b in E:
        adj[a].add(b); adj[b].add(a)
    return sorted(E), adj


# anchored motifs, as (name, atoms) with variable 'v' bound
MOTIFS_RD2 = {
    "2-path (v-x-y)": [("R", ["v", "x"]), ("R", ["x", "y"])],
    "C4 (v-x-y-z)":   [("R", ["v", "x"]), ("R", ["x", "y"]),
                       ("R", ["y", "z"]), ("R", ["z", "v"])],
}


def enumerate_embeddings(adj, v, motif):
    """All embeddings of the (undirected) motif at anchor v, as tuples of edges."""
    name = motif
    out = []
    if name == "2-path (v-x-y)":
        for x in adj[v]:
            for y in adj[x]:
                if y != v:
                    out.append((ekey(v, x), ekey(x, y)))
    else:  # C4
        for x in adj[v]:
            for y in adj[x]:
                if y == v:
                    continue
                for z in adj[y]:
                    if z in (v, x):
                        continue
                    if v in adj[z]:
                        out.append((ekey(v, x), ekey(x, y), ekey(y, z), ekey(z, v)))
    return out


def ekey(a, b):
    return (min(a, b), max(a, b))


def RD2(net_name="case2869pegase", n_anchors=40, Ks=(16, 64, 256),
        motif="2-path (v-x-y)", skew_aware=False):
    rng = random.Random(SEED)
    E, adj = load_pegase(net_name)
    atoms = MOTIFS_RD2[motif]
    d = len(atoms)
    tau = tau_star(atoms, frozenset({"v"}))
    _, shares = share_lp(atoms, frozenset({"v"}))
    U = sorted(shares)
    degs = sorted((len(adj[u]) for u in adj), reverse=True)

    # anchors: the highest-degree buses (the worst case for load skew) plus a
    # random sample, restricted to anchors with at least a few embeddings
    cand = sorted(adj, key=lambda u: -len(adj[u]))
    anchors = cand[:n_anchors // 2] + rng.sample(cand[n_anchors // 2:],
                                                 min(n_anchors // 2,
                                                     max(0, len(cand) - n_anchors // 2)))
    recs = []
    for K in Ks:
        p = {u: max(1, int(round(K ** shares[u]))) for u in U}
        Kreal = 1
        for u in U:
            Kreal *= p[u]
        coords = list(itertools.product(*[range(p[u]) for u in U]))
        ui = {u: i for i, u in enumerate(U)}
        stats = []
        for v in anchors:
            emb = enumerate_embeddings(adj, v, motif)
            if len(emb) < d:
                continue
            tuples = sorted({e for et in emb for e in et})
            if skew_aware:
                # Frequency-balanced bucketing (LPT): assign each value to the
                # currently-lightest bucket, heaviest value first.  Still a pure
                # function of the value, so detection stays deterministic; it only
                # removes the load imbalance that uniform hashing leaves behind.
                freq = {u: defaultdict(int) for u in U}
                for et in emb:
                    for slot, e in zip(atoms, et):
                        for var, val in zip(slot[1], e):
                            if var in freq:
                                freq[var][val] += 1
                h = {}
                for u in U:
                    load = [0] * p[u]
                    hu = {}
                    for val, f in sorted(freq[u].items(), key=lambda kv: -kv[1]):
                        b = min(range(p[u]), key=lambda i: load[i])
                        hu[val] = b
                        load[b] += f
                    h[u] = hu

                def hv(u, x):
                    return h[u].setdefault(x, rng.randrange(p[u]))
            else:
                h = {u: {} for u in U}

                def hv(u, x):
                    if x not in h[u]:
                        h[u][x] = rng.randrange(p[u])
                    return h[u][x]

            # placement: a retrieved edge may fill several motif slots; union them
            place = defaultdict(set)
            for et in emb:
                for slot, e in zip(atoms, et):
                    _, vs = slot
                    a, b = e
                    # the edge is used in this slot with a specific orientation;
                    # record both consistent bindings (undirected relation)
                    for (xa, xb) in ((a, b), (b, a)):
                        fixed = {}
                        ok = True
                        for var, val in zip(vs, (xa, xb)):
                            if var == "v":
                                if val != v:
                                    ok = False
                                    break
                            else:
                                fixed[ui[var]] = hv(var, val)
                        if not ok:
                            continue
                        place[e] |= {c for c in coords
                                     if all(c[i] == q for i, q in fixed.items())}
            covered = 0
            for et in emb:
                inter = None
                for e in et:
                    inter = place[e] if inter is None else (inter & place[e])
                    if not inter:
                        break
                if inter:
                    covered += 1
            rho = [len(place[e]) for e in tuples]
            loads = defaultdict(int)
            for e in tuples:
                for c in place[e]:
                    loads[c] += 1
            L = list(loads.values())
            stats.append(dict(anchor=v, deg=len(adj[v]), N=len(tuples),
                              n_emb=len(emb), P_det=covered / len(emb),
                              rho_max=max(rho), rho_bar=float(np.mean(rho)),
                              load_max=max(L), load_mean=float(np.mean(L)),
                              skew=max(L) / float(np.mean(L))))
        recs.append(dict(K_requested=K, K=Kreal, shares=p, n_anchors=len(stats),
                         min_P_det=min(s["P_det"] for s in stats),
                         mean_rho_max=float(np.mean([s["rho_max"] for s in stats])),
                         max_rho_max=max(s["rho_max"] for s in stats),
                         paper_floor=Kreal ** (1 - 1.0 / d),
                         new_floor=Kreal ** (1 - 1.0 / tau),
                         mean_skew=float(np.mean([s["skew"] for s in stats])),
                         max_skew=max(s["skew"] for s in stats),
                         per_anchor=stats[:8]))
    lk = np.log([r["K"] for r in recs])
    lr = np.log([max(r["max_rho_max"], 1) for r in recs])
    lm = np.log([max(r["mean_rho_max"], 1) for r in recs])
    return dict(measured_exponent_mean=float(np.polyfit(lk, lm, 1)[0]),
                skew_aware=skew_aware, network=net_name, n_nodes=len(adj), n_edges=len(E),
                deg_max=degs[0], deg_mean=float(np.mean(degs)),
                deg_p99=int(np.percentile(degs, 99)),
                motif=motif, d=d, tau_star_v=tau, shares=shares,
                paper_exponent=1 - 1.0 / d, predicted_exponent=1 - 1.0 / tau,
                measured_exponent=float(np.polyfit(lk, lr, 1)[0]),
                records=recs)



"""
realdata.py -- RD1/RD2: the packing law on REAL inputs.

The theory takes two real-world inputs: a QUERY (which fixes tau*_A) and a NETWORK
(which fixes the load distribution the design must survive). We test both on data we
did not generate.

RD1  Real query workload: the 22 TPC-H queries over the published TPC-H foreign-key
     schema.  For each query we compute the arity d and the fractional edge packing
     number tau*, and report how much the arity reading over-prices the defense.
     TPC-H is the standard decision-support benchmark; the schema and the table set
     of each query are fixed by the specification, and both are written out below so
     the encoding is auditable rather than asserted.

RD2  Real network topology: the PEGASE pan-European transmission networks
     (1354 / 2869 / 9241 buses), shipped with pandapower.  These are real
     infrastructure topologies -- not generated by us and not power-law by
     construction.  We plant an anchored motif, build the anchored HyperCube from the
     share LP, and measure P_det, rho_max, and the real load skew.  This is the
     stress test for Remark "skew is a certificate liability": the exponent is a
     theorem, the constants are an empirical question.

Run:  python3 realdata.py     (writes results_realdata.json)
"""
from __future__ import annotations
import itertools, json, math, os, random
from collections import defaultdict

import numpy as np
from scipy.optimize import linprog

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 20260729


# ===========================================================================
# Shared LP machinery (atoms = list of (name, [variables]))
from lp import tau_star, share_lp



# ===========================================================================
# RD1: TPC-H
# ===========================================================================
# Published TPC-H schema, join (key) attributes only.  A table is an atom; its
# variables are the primary/foreign keys through which it can join.
TPCH_SCHEMA = {
    "region":   ["regionkey"],
    "nation":   ["nationkey", "regionkey"],
    "customer": ["custkey", "nationkey"],
    "supplier": ["suppkey", "nationkey"],
    "part":     ["partkey"],
    "partsupp": ["partkey", "suppkey"],
    "orders":   ["orderkey", "custkey"],
    "lineitem": ["orderkey", "partkey", "suppkey"],
}

# Distinct tables joined by each of the 22 TPC-H queries, as specified.
# Self-joins (e.g. Q21's three lineitem aliases, Q7/Q8's two nation aliases) are
# collapsed to the distinct table; that can only DECREASE d and tau*, so the
# over-pricing figures below are conservative.
TPCH_QUERIES = {
    "Q1":  ["lineitem"],
    "Q2":  ["part", "supplier", "partsupp", "nation", "region"],
    "Q3":  ["customer", "orders", "lineitem"],
    "Q4":  ["orders", "lineitem"],
    "Q5":  ["customer", "orders", "lineitem", "supplier", "nation", "region"],
    "Q6":  ["lineitem"],
    "Q7":  ["supplier", "lineitem", "orders", "customer", "nation"],
    "Q8":  ["part", "supplier", "lineitem", "orders", "customer", "nation", "region"],
    "Q9":  ["part", "supplier", "lineitem", "partsupp", "orders", "nation"],
    "Q10": ["customer", "orders", "lineitem", "nation"],
    "Q11": ["partsupp", "supplier", "nation"],
    "Q12": ["orders", "lineitem"],
    "Q13": ["customer", "orders"],
    "Q14": ["lineitem", "part"],
    "Q15": ["supplier", "lineitem"],
    "Q16": ["partsupp", "part", "supplier"],
    "Q17": ["lineitem", "part"],
    "Q18": ["customer", "orders", "lineitem"],
    "Q19": ["lineitem", "part"],
    "Q20": ["supplier", "nation", "partsupp", "part", "lineitem"],
    "Q21": ["supplier", "lineitem", "orders", "nation"],
    "Q22": ["customer", "orders"],
}

# Keys pinned by a constant equality predicate in the published query text.
# (Anchoring REMOVES a packing constraint, so it can only raise tau* -- i.e. it
# makes the defense more expensive, never cheaper.  Reported alongside the
# unanchored value so both ends of the range are visible.)
TPCH_ANCHORS = {
    "Q2": {"regionkey"}, "Q5": {"regionkey"}, "Q8": {"regionkey"},
    "Q11": {"nationkey"}, "Q20": {"nationkey"}, "Q21": {"nationkey"},
    "Q7": {"nationkey"}, "Q9": set(), "Q17": {"partkey"}, "Q19": {"partkey"},
}


def query_atoms(tables):
    """Atoms for a query = its tables, restricted to join variables that are
    actually shared inside this query (a key appearing in one table only cannot
    be a join variable here)."""
    cnt = defaultdict(int)
    for t in tables:
        for v in TPCH_SCHEMA[t]:
            cnt[v] += 1
    return [(t, [v for v in TPCH_SCHEMA[t] if cnt[v] >= 2]) for t in tables]


def RD1(K_ref=1024):
    rows = []
    for q, tables in TPCH_QUERIES.items():
        atoms = query_atoms(tables)
        d = len(atoms)
        joinvars = sorted({v for _, vs in atoms for v in vs})
        if d == 1 or not joinvars:
            rows.append(dict(query=q, tables=tables, d=d, join_vars=joinvars,
                             tau_star=float(d), tau_star_anchored=float(d),
                             lp_duality_gap=0.0, overprice_exponent=0.0,
                             budget_ratio_at_K=1.0, ctx_rule_gamma1="n/a",
                             note="single-relation query; no conjunction"))
            continue
        t0 = tau_star(atoms)
        A = TPCH_ANCHORS.get(q, set())
        tA = tau_star(atoms, frozenset(A))
        val, shares = share_lp(atoms)
        gap = abs(val - 1.0 / t0)
        # over-pricing of the arity reading, evaluated at the anchored (harder) tau*
        ov = 1.0 / tA - 1.0 / d
        rows.append(dict(
            query=q, tables=tables, d=d, join_vars=joinvars,
            anchor=sorted(A), tau_star=t0, tau_star_anchored=tA,
            share_lp_value=val, lp_duality_gap=gap,
            paper_exponent=1 - 1.0 / d, true_exponent=1 - 1.0 / tA,
            overprice_exponent=ov, budget_ratio_at_K=K_ref ** ov,
            ctx_rule_gamma1=("largest cells" if tA - 1 > 1 else
                             "scale-free" if abs(tA - 2) < 1e-9 else "smallest cells"),
            ctx_rule_arity_gamma1=("largest cells" if d - 1 > 1 else
                                   "scale-free" if d == 2 else "smallest cells"),
            shares={k: round(v, 4) for k, v in shares.items()}))
    multi = [r for r in rows if r["d"] > 1]
    strict = [r for r in multi if r["tau_star_anchored"] < r["d"] - 1e-9]
    flipped = [r for r in multi
               if r.get("ctx_rule_gamma1") != r.get("ctx_rule_arity_gamma1")]
    return dict(
        K_ref=K_ref, n_queries=len(rows), n_multi_relation=len(multi),
        n_tau_lt_d=len(strict),
        frac_overpriced=len(strict) / len(multi),
        median_budget_ratio=float(np.median([r["budget_ratio_at_K"] for r in multi])),
        max_budget_ratio=float(max(r["budget_ratio_at_K"] for r in multi)),
        argmax_query=max(multi, key=lambda r: r["budget_ratio_at_K"])["query"],
        max_lp_duality_gap=float(max(r["lp_duality_gap"] for r in multi)),
        n_context_rule_flipped=len(flipped),
        context_rule_flipped=[r["query"] for r in flipped],
        rows=rows)


